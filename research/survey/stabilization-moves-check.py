        from sympy import Matrix
        from sympy.matrices.normalforms import hermite_normal_form

        def hnf_basis(rows, n):
            """Basis of the lattice generated by `rows` in Z^n as (pivot, column)."""
            if not rows:
                return []
            A = Matrix(n, len(rows), lambda i, j: int(rows[j][i]))
            H = hermite_normal_form(A)
            basis = []
            for j in range(H.cols):
                col = [int(H[i, j]) for i in range(n)]
                nz = [i for i in range(n) if col[i] != 0]
                if nz:
                    basis.append((nz[-1], col))
            return basis

        def in_lattice(v, basis, n):
            r = len(basis)
            x = [0] * r
            for j in range(r - 1, -1, -1):
                p, col = basis[j]
                num = v[p] - sum(basis[k][1][p] * x[k] for k in range(j + 1, r))
                if num % col[p] != 0:
                    return False
                x[j] = num // col[p]
            for i in range(n):
                if sum(basis[k][1][i] * x[k] for k in range(r)) != v[i]:
                    return False
            return True

        def invariant(P):
            n, rels = P
            rows = [expvec(r, n) for r in rels]
            basis = hnf_basis(rows, n)
            dim = 0
            for i in range(n):
                v = [0] * n
                v[i] = 1
                if in_lattice(v, basis, n):
                    dim += 1
            return len(basis) - dim

