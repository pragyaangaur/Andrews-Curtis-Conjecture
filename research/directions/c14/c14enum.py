#!/usr/bin/env python3
"""Canonical enumeration of rank-2 balanced presentations, and finite-quotient
witnesses.  Canonical form: each relator freely and cyclically reduced, minimal
under cyclic rotation and inversion; relators ordered by (length, word)."""
import itertools
import c14lib as L

_CACHE = {}


def canonical_words(k):
    if k in _CACHE:
        return _CACHE[k]
    out = []
    for w in itertools.product((1, -1, 2, -2), repeat=k):
        if L.red(w) != w:
            continue
        if w[0] == -w[-1]:
            continue
        if w != L.canon_word(w):
            continue
        out.append(w)
    _CACHE[k] = out
    return out


def presentations_exact(l):
    """canonical pairs with len1+len2 == l, one per class under relator order,
    cyclic rotation and inversion"""
    for l1 in range(1, l // 2 + 1):
        l2 = l - l1
        w1s = canonical_words(l1)
        w2s = canonical_words(l2)
        for w1 in w1s:
            for w2 in w2s:
                if l1 == l2 and w2 < w1:
                    continue
                yield (w1, w2)


# ------------------------------------------------------------ finite groups
def perm_mul(p, q):
    return tuple(p[q[i]] for i in range(len(p)))


def closure(gens):
    n = len(gens[0])
    e = tuple(range(n))
    el = {e}
    fr = [e]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = perm_mul(x, g)
                if y not in el:
                    el.add(y)
                    nf.append(y)
        fr = nf
    return sorted(el)


def table(gens):
    el = closure(gens)
    ix = {e: i for i, e in enumerate(el)}
    return el, [[ix[perm_mul(e, f)] for f in el] for e in el]


def inv_table(tab):
    n = len(tab)
    out = [0] * n
    for i in range(n):
        for k in range(n):
            if tab[i][k] == 0:
                out[i] = k
                break
    return out


def mat_mul(x, y, p):
    (a, b), (c, d) = x
    (e, f), (g, h) = y
    return (((a * e + b * g) % p, (a * f + b * h) % p),
            ((c * e + d * g) % p, (c * f + d * h) % p))


def sl2(p):
    """elements of SL(2,p), as pairs of pairs"""
    out = []
    for a in range(p):
        for b in range(p):
            for c in range(p):
                for d in range(p):
                    if (a * d - b * c) % p == 1:
                        out.append(((a, b), (c, d)))
    return out


def sl2_table(p):
    el = sl2(p)
    ix = {e: i for i, e in enumerate(el)}
    tab = [[ix[mat_mul(e, f, p)] for f in el] for e in el]
    return el, tab


GROUPS = []


def normalize(name, el, tab):
    """relabel so that the identity element has index 0"""
    n = len(tab)
    ident = None
    for i in range(n):
        if all(tab[i][j] == j for j in range(n)):
            ident = i
            break
    assert ident is not None, name
    ren = [0] * n
    ren[ident] = 0
    k = 1
    for i in range(n):
        if i != ident:
            ren[i] = k
            k += 1
    inv = [0] * n
    for i in range(n):
        inv[ren[i]] = i
    tab2 = [[0] * n for _ in range(n)]
    for i in range(n):
        ri, ti = ren[i], tab[i]
        for j in range(n):
            tab2[ri][ren[j]] = ren[ti[j]]
    assert all(tab2[0][j] == j for j in range(n)), name
    return (name, n, tab2, inv_table(tab2))


def psl27_gens():
    """PSL(2,7) acting on the eight points of P^1(F_7), infinity = 7,
    generated by x -> x+1 and x -> -1/x."""
    p = 7

    def act(M, x):
        a, b, c, d = M
        if x == p:
            if c % p == 0:
                return p
            return a * pow(c, p - 2, p) % p
        num = (a * x + b) % p
        den = (c * x + d) % p
        if den == 0:
            return p
        return num * pow(den, p - 2, p) % p

    def perm(M):
        return tuple(act(M, x) for x in range(p + 1))

    return [perm((1, 1, 0, 1)), perm((0, -1 % p, 1, 0))]


def quat_mul(x, y):
    (a, b), (c, d) = x, y
    return ((a + (c if b == 0 else -c)) % 4, (b + d) % 2)


def init_groups():
    if GROUPS:
        return GROUPS
    specs = [
        ('S3', [(1, 0, 2), (0, 2, 1)]),
        ('D8', [(1, 2, 3, 0), (1, 0, 3, 2)]),
        ('A4', [(1, 2, 0, 3), (1, 0, 3, 2)]),
        ('S4', [(1, 2, 3, 0), (1, 0, 2, 3)]),
        ('A5', [(1, 2, 3, 4, 0), (1, 2, 0, 3, 4)]),
        ('S5', [(1, 2, 3, 4, 0), (0, 1, 3, 2, 4)]),
        ('PSL27', psl27_gens()),
        ('A6', [(1, 2, 0, 3, 4, 5), (1, 3, 2, 0, 4, 5), (1, 4, 2, 3, 0, 5), (1, 5, 2, 3, 4, 0)]),
    ]
    expected = {'S3': 6, 'D8': 8, 'A4': 12, 'S4': 24, 'A5': 60, 'S5': 120,
                'PSL27': 168, 'A6': 360}
    for name, gens in specs:
        el, tab = table(gens)
        assert len(el) == expected[name], (name, len(el))
        GROUPS.append(normalize(name, el, tab))
    # Q8 from the quaternion formula
    els = [(a, b) for b in (0, 1) for a in range(4)]
    ix = {e: i for i, e in enumerate(els)}
    tab = [[ix[quat_mul(e, f)] for f in els] for e in els]
    GROUPS.append(normalize('Q8', els, tab))
    # SL(2,5) from matrices over F5
    els2, tab2 = sl2_table(5)
    assert len(els2) == 120
    GROUPS.append(normalize('SL25', els2, tab2))
    return GROUPS


def eval_word(r, tab, invs, ia, ib):
    idx = 0
    for x in r:
        if x == 1:
            idx = tab[idx][ia]
        elif x == -1:
            idx = tab[idx][invs[ia]]
        elif x == 2:
            idx = tab[idx][ib]
        else:
            idx = tab[idx][invs[ib]]
    return idx


def quotient_witness(t, names=None, want_order=None):
    """Search for a homomorphism to a small group whose image is nontrivial.
    Returns (name, order, ia, ib, img_order) or None."""
    for name, n, tab, invs in init_groups():
        if names is not None and name not in names:
            continue
        for ia in range(n):
            for ib in range(n):
                if ia == 0 and ib == 0:
                    continue
                ok = True
                for r in t:
                    if eval_word(r, tab, invs, ia, ib) != 0:
                        ok = False
                        break
                if ok:
                    if want_order is None:
                        return (name, n, ia, ib)
                    # order of the image of <ia,ib>
                    el = closure_gen(tab, [ia, ib])
                    if len(el) == want_order:
                        return (name, n, ia, ib, len(el))
    return None


def closure_gen(tab, gens):
    el = {0}
    fr = [0]
    while fr:
        nf = []
        for x in fr:
            for g in gens:
                y = tab[x][g]
                if y not in el:
                    el.add(y)
                    nf.append(y)
        fr = nf
    return el
